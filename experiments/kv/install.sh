#!/bin/bash
# KV pilot install (reports/M5-pilot-kv.md §2): copy our builds to both guests (standing grant A1), print sha256s.
#   $VM_PLAIN (default /home/comsys/kv2):  bin/kv-server + lib/* (builds/kv/2: hwcc-flavor Megalon), bin/kv-node.sh,
#                                         cfg/cxl_region.yaml, cfg/megalon.yaml       (all-HWcc, page MSI)
#   $VM_MEG   (default /home/comsys/kvm2): the same from builds/kv-megalon/2 (Megalon build 70)   (Megalon)
#   cfg/megalon.yaml = systems/megalon/kv-2vm.yaml with key_space/slots/logical_scr_size from
#   `kv-server --print-sizes --keys $KEYS` (default 4000000), written to $LOG.megalon.yaml first.
# No data goes to the guests (values are generated by the plugin and the initial load). Refuses existing install dirs.
# usage: install.sh <log file>
set -euo pipefail
P=/home/comsys/sungsu/destijl-control C=$P/CXL_SWMC LOG=$1
KEYS=${KEYS:-4000000} BP=${PLAIN_BUILD:-$P/builds/kv/2} BM=${MEG_BUILD:-$P/builds/kv-megalon/2}
VP=${VM_PLAIN:-/home/comsys/kv2} VM=${VM_MEG:-/home/comsys/kvm2}
SSH="ssh -o BatchMode=yes -o ConnectTimeout=8"
CFG=$LOG.megalon.yaml
[ -e "$CFG" ] && { echo "refusing: $CFG exists"; exit 2; }
eval "$("$BP/bin/kv-server" --print-sizes --keys "$KEYS" | grep -E '^(key_space|slots|logical_scr_size)=')"
sed -e "s/^key_space:.*/key_space: $key_space/" -e "s/^slots:.*/slots: $slots/" \
    -e "s/^logical_scr_size:.*/logical_scr_size: $logical_scr_size/" "$C/systems/megalon/kv-2vm.yaml" > "$CFG"
for ip in 192.168.122.100 192.168.122.101; do
  $SSH comsys@$ip "test ! -e $VP && test ! -e $VM && mkdir -p $VP/bin $VP/lib $VP/cfg $VM/bin $VM/lib $VM/cfg" < /dev/null
  for pair in "$BP $VP" "$BM $VM"; do
    set -- $pair
    scp -q "$1/bin/kv-server" "$C/scripts/guest/kv-node.sh" comsys@$ip:"$2/bin/"
    scp -q "$1"/lib/* comsys@$ip:"$2/lib/"
    scp -q "$C/config/cxl_region.yaml" comsys@$ip:"$2/cfg/"
    scp -q "$CFG" comsys@$ip:"$2/cfg/megalon.yaml"
  done
  { echo "== $ip $(date -Is)"; $SSH comsys@$ip "cd /home/comsys && sha256sum ${VP#/home/comsys/}/bin/* ${VP#/home/comsys/}/lib/* ${VP#/home/comsys/}/cfg/* ${VM#/home/comsys/}/bin/* ${VM#/home/comsys/}/lib/* ${VM#/home/comsys/}/cfg/*; echo ldd_not_found=\$(ldd $VP/bin/kv-server $VP/lib/libkv-megalon.so $VM/bin/kv-server $VM/lib/libkv-megalon.so | grep -c 'not found')" < /dev/null; } | tee -a "$LOG"
done
{ echo "== Host expected"; (cd "$BP" && sha256sum bin/kv-server lib/*); (cd "$BM" && sha256sum bin/kv-server lib/*)
  sha256sum "$C/scripts/guest/kv-node.sh" "$C/config/cxl_region.yaml" "$CFG"; } | tee -a "$LOG"
